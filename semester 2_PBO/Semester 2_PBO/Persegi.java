public class Persegi {
    int panjang;//Deklarasi variabel panjang dengan tipe data integer
    int lebar;//Deklarasi variabel lebar dengan tipe data integer

    public double luasPersegi() {
        //Deklarasikan method bernama luasPersegi() dengan tipe data double
        double luas = panjang*lebar;
        //Menghitung luas dengan rumus lalu menyimpannya ke luas
        return luas;//mengembalikan luas
    }
}